   private void advancedGolemRecipes(RecipeOutput consumer) {
      for (ItemLike itemLike : this.basicGolems()) {
         ItemStack result = this.advancedGolemStack(itemLike);
         Ingredient central = DifferenceIngredient.of(Ingredient.of(new ItemLike[]{itemLike}), DataComponentIngredient.of(true, result));
         InfusionRecipeBuilder.infusion("advanced_golem", result)
            .aspect(Aspect.MIND, 8)
            .aspect(Aspect.SENSES, 8)
            .aspect(Aspect.LIFE, 8)
            .instability(3)
            .central(central)
            .requires(Items.REDSTONE)
            .requires(Items.GLOWSTONE_DUST)
            .requires(Items.GUNPOWDER)
            .requires((ItemLike)ModItems.JAR.get())
            .requires((ItemLike)ModItems.ZOMBIE_BRAIN.get())
            .save(consumer, Thaumcraft.location("infusion/advanced_golem_" + this.golemIdSuffix(itemLike)));
      }
   }

