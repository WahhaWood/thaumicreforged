   private static ItemStack matrixUpdate(byte metaUpdate) {
      ItemStack stack = new ItemStack((ItemLike)ModItems.RUNIC_MATRIX.get());
      CompoundTag tag = new CompoundTag();
      tag.putBoolean("isInfo", true);
      tag.putByte("metaUpdate", metaUpdate);
      ItemStackData.setTag(stack, tag);
      return stack;
   }

   private ItemStack advancedGolemStack(ItemLike itemLike) {
      ItemStack stack = new ItemStack(itemLike);
      ItemStackData.getOrCreateTag(stack).putByte("advanced", (byte)1);
      return stack;
   }

